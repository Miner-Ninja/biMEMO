"""Summary distiller agent for synthesizing records into summaries.

Receives accumulated records and calls a Qwen3 model to
generate structured JSON summaries capturing main points and
supporting reasons. Validates output against the Summary
schema. Provides the full processing pipeline with tainted
filtering and ContentFilter integration.

The summary distiller now writes memory through the DB proxy path only.
"""

