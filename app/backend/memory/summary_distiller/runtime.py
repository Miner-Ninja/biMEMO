def _filter_summary_fields(
    summary: Summary,
    records: list[Record] | None = None,
) -> Summary | None:
    """Filter all structured summary fields before persistence.

    Args:
        summary: Raw summary generated by the distiller model.
        records: Source records used for scope fallback decisions.

    Returns:
        Filtered summary, or ``None`` when any field is unsafe.
    """
    filtered_main_point = filter_output(summary.main_point)
    if filtered_main_point.injection_flagged:
        return None

    filtered_based_on: list[str] = []
    for based_on_item in summary.based_on[:MAX_FILTERED_BASED_ON_ITEMS]:
        filtered_based_on_item = filter_output(based_on_item)
        if filtered_based_on_item.injection_flagged:
            return None
        filtered_based_on.append(filtered_based_on_item.text)
    filtered_based_on = _compress_based_on_reasons(filtered_based_on)

    inferred_scope = _infer_summary_scope(summary, records)

    return Summary(
        main_point=filtered_main_point.text,
        based_on=filtered_based_on,
        trust_level=summary.trust_level,
        scope=inferred_scope,
        record_relations=summary.record_relations,
    )


async def synthesize_observations(
    provider: OllamaProvider,
    records: list[Record],
    *,
    trace_context: dict[str, object] | None = None,
) -> Summary | None:
    """Synthesize records into a summary.

    Calls the dialog recorder model to generate a JSON summary.
    Returns None if the LLM output fails validation.

    Args:
        provider: OllamaProvider for LLM inference.
        records: List of records to synthesize.
        trace_context: Optional diagnostic bag that collects prompt,
            raw output, decision, and errors for the trace log.

    Returns:
        Summary if valid, None on failure.
    """
    combined = _build_summary_input(records)
    chat_messages = [
        ChatMessage(role="system", content=DISTILLER_SYSTEM_PROMPT),
        ChatMessage(role="user", content=combined),
    ]
    if trace_context is not None:
        trace_context["prompt"] = [
            {"role": message.role, "content": message.content}
            for message in chat_messages
        ]
        trace_context["model"] = provider.dialog_recorder_model
    try:
        logger.info(
            "Distiller LLM call started (model=%s)",
            provider.dialog_recorder_model,
        )
        response = await provider.chat(
            chat_messages,
            model=provider.dialog_recorder_model,
            max_tokens=DISTILLER_MAX_TOKENS,
            temperature=DISTILLER_TEMPERATURE,
            enable_thinking=False,
        )
        if trace_context is not None:
            trace_context["raw_output"] = response.content
        summary = _parse_distillation(response.content)
        if summary is None and trace_context is not None:
            trace_context["decision"] = TRACE_DECISION_PARSE_FAILED
        return summary
    except Exception:
        if trace_context is not None:
            trace_context["decision"] = TRACE_DECISION_LLM_ERROR
            trace_context["error"] = "Distiller LLM call failed"
        logger.exception("Distiller LLM call failed")
        return None


def _build_distiller_trace_entry(
    records: list[Record],
    record_ids: list[str],
    trace_context: dict[str, object],
    decision: str,
) -> dict[str, object]:
    """Build a stable distiller trace entry for diagnostics."""
    summary = trace_context.get("summary")
    filtered_distillation = trace_context.get("filtered_distillation")
    serialized_distillation = (
        filtered_distillation if isinstance(filtered_distillation, Summary) else summary
    )

    return {
        "decision": decision,
        "model": trace_context.get("model"),
        "record_count": len(records),
        "source_record_ids": record_ids,
        "records": [
            {
                "summary": record.summary,
                "key_facts": record.key_facts,
                "action_items": record.action_items,
            }
            for record in records
        ],
        "prompt": trace_context.get("prompt", []),
        "raw_output": trace_context.get("raw_output", ""),
        "main_point": (
            serialized_distillation.main_point
            if isinstance(serialized_distillation, Summary)
            else ""
        ),
        "based_on": (
            serialized_distillation.based_on
            if isinstance(serialized_distillation, Summary)
            else []
        ),
        "trust_level": (
            serialized_distillation.trust_level.value
            if isinstance(serialized_distillation, Summary)
            and hasattr(serialized_distillation.trust_level, "value")
            else (
                serialized_distillation.trust_level
                if isinstance(serialized_distillation, Summary)
                else ""
            )
        ),
        "scope": (
            serialized_distillation.scope.value
            if isinstance(serialized_distillation, Summary)
            and hasattr(serialized_distillation.scope, "value")
            else (
                serialized_distillation.scope
                if isinstance(serialized_distillation, Summary)
                else ""
            )
        ),
        "record_relations": (
            [
                relation.value if hasattr(relation, "value") else str(relation)
                for relation in serialized_distillation.record_relations
            ]
            if isinstance(serialized_distillation, Summary)
            else []
        ),
        "summary_id": trace_context.get("summary_id"),
        "original_scope": trace_context.get("original_scope", ""),
        "scope_adjustment_reason": trace_context.get("scope_adjustment_reason", ""),
        "error": trace_context.get("error", ""),
        "detail": trace_context.get("detail", ""),
    }


async def _append_distiller_trace(
    db_client: object,
    records: list[Record],
    record_ids: list[str],
    trace_context: dict[str, object],
    decision: str,
) -> None:
    """Append one distiller trace entry."""
    entry = _build_distiller_trace_entry(
        records,
        record_ids,
        trace_context,
        decision,
    )
    append_distiller_trace(entry)
    try:
        await db_client.write_summary_processing_diagnostic(
            decision=decision,
            summary_id=str(entry.get("summary_id", "")),
            model=str(entry.get("model", "")),
            record_count=int(entry.get("record_count", 0)),
            source_record_ids=[str(item) for item in record_ids],
            records=list(entry.get("records", [])),
            prompt=list(entry.get("prompt", [])),
            raw_output=str(entry.get("raw_output", "")),
            main_point=str(entry.get("main_point", "")),
            based_on=[str(item) for item in entry.get("based_on", [])],
            trust_level=str(entry.get("trust_level", "")),
            scope=str(entry.get("scope", "")),
            record_relations=[str(item) for item in entry.get("record_relations", [])],
            original_scope=str(entry.get("original_scope", "")),
            scope_adjustment_reason=str(entry.get("scope_adjustment_reason", "")),
            error=str(entry.get("error", "")),
            detail=str(entry.get("detail", "")),
        )
    except Exception:
        logger.warning(
            "Failed to write summary processing diagnostic",
            exc_info=True,
        )


async def _load_recent_summary_records(
    db_client: object,
    limit: int = RECENT_DISTILLATION_DEDUP_LIMIT,
) -> list[dict[str, object]]:
    """Load recent summaries with provenance metadata through the DB proxy."""
    return await db_client.list_summaries_full(limit=limit, offset=0)


def _decode_record_json_field(value: object) -> object:
    """Decode one distiller record field that may already be parsed."""
    return json.loads(value) if isinstance(value, str) else value


def _build_distiller_records(
    rows: list[dict[str, object]],
) -> tuple[list[Record], list[str]]:
    """Convert DB rows into distiller Record objects and source IDs."""
    records: list[Record] = []
    record_ids: list[str] = []
    valid_memory_kinds = {kind.value: kind for kind in RecordKind}
    for row in rows:
        obs_id = str(row["id"])
        memory_kinds_data = _decode_record_json_field(row.get("memory_kinds", "[]"))
        memory_kinds = [
            valid_memory_kinds[memory_kind]
            for memory_kind in memory_kinds_data
            if memory_kind in valid_memory_kinds
        ]
        record_ids.append(obs_id)
        records.append(
            Record(
                summary=str(row["summary"]),
                key_facts=_decode_record_json_field(row.get("key_facts", "[]")),
                action_items=_decode_record_json_field(row.get("action_items", "[]")),
                memory_kinds=memory_kinds,
            )
        )
    return records, record_ids


async def _synthesize_distiller_summary(
    provider: OllamaProvider,
    db_client: object,
    records: list[Record],
    record_ids: list[str],
    trace_context: dict[str, object],
) -> Summary | None:
    """Run synthesis and handle the early trace path on parse failure."""
    summary = await synthesize_observations(
        provider,
        records,
        trace_context=trace_context,
    )
    if summary is None:
        await _append_distiller_trace(
            db_client,
            records,
            record_ids,
            trace_context,
            str(trace_context.get("decision", TRACE_DECISION_PARSE_FAILED)),
        )
        return None
    trace_context["summary"] = summary
    return summary


async def _reject_filtered_distillation(
    db_client: object,
    records: list[Record],
    record_ids: list[str],
    trace_context: dict[str, object],
    filtered_distillation: Summary,
    *,
    decision: str,
    detail: str,
    log_message: str,
) -> None:
    """Record one rejected distiller result and append its trace entry."""
    logger.info(log_message)
    trace_context["filtered_distillation"] = filtered_distillation
    trace_context["detail"] = detail
    await _append_distiller_trace(
        db_client,
        records,
        record_ids,
        trace_context,
        decision,
    )


async def _reject_if_filtered_distillation_matches_rule(
    *,
    rejection_rule: _DistillationRejectionRule,
    matched: bool,
    db_client: object,
    records: list[Record],
    record_ids: list[str],
    trace_context: dict[str, object],
    filtered_distillation: Summary,
) -> bool:
    """Reject one filtered distillation when the configured rule matches."""
    if not matched:
        return False
    await _reject_filtered_distillation(
        db_client,
        records,
        record_ids,
        trace_context,
        filtered_distillation,
        decision=rejection_rule.decision,
        detail=rejection_rule.detail,
        log_message=rejection_rule.log_message,
    )
    return True


async def _reject_unsafe_distillation(
    db_client: object,
    records: list[Record],
    record_ids: list[str],
    trace_context: dict[str, object],
) -> None:
    """Record one unsafe-output rejection and append its trace entry."""
    logger.warning("Distiller output injection detected, discarding")
    trace_context["detail"] = (
        "Summary was discarded because filtered output looked unsafe."
    )
    await _append_distiller_trace(
        db_client,
        records,
        record_ids,
        trace_context,
        TRACE_DECISION_UNSAFE_OUTPUT,
    )


def _distillation_trust_level_value(summary: Summary) -> str:
    """Return the serialized trust-level value for one summary."""
    return (
        summary.trust_level.value
        if hasattr(summary.trust_level, "value")
        else str(summary.trust_level)
    )


def _distillation_scope_value(summary: Summary) -> str:
    """Return the serialized scope value for one summary."""
    return (
        summary.scope.value if hasattr(summary.scope, "value") else str(summary.scope)
    )


async def _merge_duplicate_distillation(
    db_client: object,
    duplicate_distillation: dict[str, object],
    filtered_distillation: Summary,
    record_ids: list[str],
    typed_relations: list[object],
) -> bool:
    """Merge one duplicate distillation into an existing stored summary."""
    return await db_client.merge_summary_sources(
        str(duplicate_distillation.get("id", "")),
        main_point=filtered_distillation.main_point,
        based_on=filtered_distillation.based_on,
        trust_level=_distillation_trust_level_value(filtered_distillation),
        summary_scope=_distillation_scope_value(filtered_distillation),
        trust_level_score=get_trust_level_score(
            _distillation_trust_level_value(filtered_distillation)
        ),
        source_record_ids=record_ids,
        record_relations=typed_relations,
    )


async def _trace_duplicate_distillation_result(
    db_client: object,
    records: list[Record],
    record_ids: list[str],
    trace_context: dict[str, object],
    duplicate_distillation: dict[str, object],
    merged: bool,
) -> str | None:
    """Write trace output for one duplicate-distillation decision."""
    duplicate_id = str(duplicate_distillation.get("id", ""))
    trace_context["summary_id"] = duplicate_id
    trace_context["detail"] = (
        "Summary matched recent memory and its source records were "
        "merged into the existing summary."
    )
    await _append_distiller_trace(
        db_client,
        records,
        record_ids,
        trace_context,
        (
            TRACE_DECISION_MERGED_INTO_EXISTING
            if merged
            else TRACE_DECISION_DUPLICATE_DISTILLATION
        ),
    )
    return duplicate_id if merged else None


async def _store_new_distillation(
    db_client: object,
    filtered_distillation: Summary,
    record_ids: list[str],
    typed_relations: list[object],
) -> str:
    """Persist one new distillation summary through the DB proxy."""
    return await db_client.save_summary(
        main_point=filtered_distillation.main_point,
        based_on=filtered_distillation.based_on,
        trust_level=_distillation_trust_level_value(filtered_distillation),
        summary_scope=_distillation_scope_value(filtered_distillation),
        source_record_ids=record_ids,
        record_relations=typed_relations,
    )


async def _publish_distillation_event(
    event_bus: MemoryEventBus | None,
    summary_id: str,
    filtered_distillation: Summary,
    record_count: int,
) -> None:
    """Publish the distiller completion event when an event bus is present."""
    if event_bus is None:
        return
    await event_bus.publish(
        {
            "type": "distiller",
            "summary_id": summary_id,
            "main_point": filtered_distillation.main_point,
            "based_on": filtered_distillation.based_on,
            "record_count": record_count,
        }
    )


def _apply_scope_downgrade_if_needed(
    filtered_distillation: Summary,
    records: list[Record],
    trace_context: dict[str, object],
) -> Summary:
    """Downgrade long-term scope when temporary signals contradict it."""
    if not _should_downgrade_long_term_scope_by_time_signals(
        filtered_distillation,
        records,
    ):
        return filtered_distillation
    logger.info("Distiller downgraded long-term scope due to temporary signals")
    trace_context["original_scope"] = filtered_distillation.scope.value
    trace_context["scope_adjustment_reason"] = (
        TRACE_SCOPE_ADJUSTMENT_BY_TIME_SIGNALS_AND_LLM_MISMATCH
    )
    trace_context["detail"] = (
        "Long-term scope was downgraded because the summary text used "
        "temporary or non-persistent language that contradicted durable "
        "preference signals in the source records."
    )
    return filtered_distillation.model_copy(update={"scope": SummaryScope.SHORT_TERM})


async def process_summary(
    provider: OllamaProvider,
    db_client: object,
    event_bus: MemoryEventBus | None = None,
) -> str | None:
    """Run the SummaryDistiller pipeline through the DB proxy path only."""
    rows = await db_client.fetch_untainted_records()
    if not rows:
        logger.info("No untainted records for summary")
        await _append_distiller_trace(
            db_client,
            [],
            [],
            {"detail": "No untainted records were available for summary."},
            TRACE_DECISION_NO_OBSERVATIONS,
        )
        return None

    records, record_ids = _build_distiller_records(rows)

    trace_context: dict[str, object] = {}
    summary = await _synthesize_distiller_summary(
        provider,
        db_client,
        records,
        record_ids,
        trace_context,
    )
    if summary is None:
        return None

    filtered_distillation = _filter_summary_fields(summary, records)
    if filtered_distillation is None:
        await _reject_unsafe_distillation(
            db_client,
            records,
            record_ids,
            trace_context,
        )
        return None
    if await _reject_if_filtered_distillation_matches_rule(
        rejection_rule=_DistillationRejectionRule(
            decision=TRACE_DECISION_OVERREACHING_SHORT_TERM,
            detail=(
                "Short-term summary tried to erase a durable preference even "
                "though the source records still contained a future-facing "
                "preference signal."
            ),
            log_message="Distiller skipped overreaching short-term summary",
        ),
        matched=_is_overreaching_short_term_distillation(
            filtered_distillation, records
        ),
        db_client=db_client,
        records=records,
        record_ids=record_ids,
        trace_context=trace_context,
        filtered_distillation=filtered_distillation,
    ):
        return None
    if await _reject_if_filtered_distillation_matches_rule(
        rejection_rule=_DistillationRejectionRule(
            decision=TRACE_DECISION_OVERREACHING_REVERSION,
            detail=(
                "Summary tried to turn an active future-facing detailed "
                "preference into temporary session context and restore the old "
                "concise baseline as the default."
            ),
            log_message="Distiller skipped overreaching preference reversion",
        ),
        matched=_is_overreaching_reversion_distillation(filtered_distillation, records),
        db_client=db_client,
        records=records,
        record_ids=record_ids,
        trace_context=trace_context,
        filtered_distillation=filtered_distillation,
    ):
        return None
    filtered_distillation = _apply_scope_downgrade_if_needed(
        filtered_distillation,
        records,
        trace_context,
    )
    trace_context["filtered_distillation"] = filtered_distillation

    recent_distillations = await _load_recent_summary_records(db_client)
    duplicate_distillation = _find_duplicate_summary_record(
        filtered_distillation.main_point,
        recent_distillations,
    )
    typed_relations = _build_typed_relations(
        record_ids,
        filtered_distillation.record_relations,
        records=records,
        summary=filtered_distillation,
    )
    if duplicate_distillation is not None:
        merged = await _merge_duplicate_distillation(
            db_client,
            duplicate_distillation,
            filtered_distillation,
            record_ids,
            typed_relations,
        )
        return await _trace_duplicate_distillation_result(
            db_client,
            records,
            record_ids,
            trace_context,
            duplicate_distillation,
            merged,
        )

    summary_id = await _store_new_distillation(
        db_client,
        filtered_distillation,
        record_ids=record_ids,
        typed_relations=typed_relations,
    )
    trace_context["summary_id"] = summary_id
    await _append_distiller_trace(
        db_client,
        records,
        record_ids,
        trace_context,
        TRACE_DECISION_STORED,
    )
    await _publish_distillation_event(
        event_bus,
        summary_id,
        filtered_distillation,
        len(record_ids),
    )

    return summary_id
