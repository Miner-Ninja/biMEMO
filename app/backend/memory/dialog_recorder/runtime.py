"""Dialog recorder agent for compressing messages into records.

Receives conversation messages, calls a small Qwen3 model via
OllamaProvider to generate structured records. Validates
output against the Record schema and discards invalid results.
Provides the full processing pipeline with ContentFilter integration,
rate limiting, tainted session flagging, and embedding generation.

The dialog recorder writes memory through the DB proxy path only.
"""

