def _filter_record_fields(
    record: Record,
) -> Record | None:
    """Filter all structured record fields before persistence.

    Honors the AssistantPolicy `memory.sanitize_before_save`
    toggle: when off, the record is stored as produced by the
    recorder model.

    Args:
        record: Raw record generated by the dialog recorder model.

    Returns:
        Filtered record, or ``None`` when any field is unsafe.
    """
    if not get_policy().get_bool(_KEY_SANITIZE_BEFORE_SAVE):
        return record

    filtered_summary = filter_output(record.summary)
    if filtered_summary.injection_flagged:
        return None

    filtered_key_facts: list[str] = []
    for key_fact in record.key_facts[:MAX_FILTERED_FIELD_ITEMS]:
        filtered_key_fact = filter_output(key_fact)
        if filtered_key_fact.injection_flagged:
            return None
        filtered_key_facts.append(filtered_key_fact.text)

    filtered_action_items: list[str] = []
    for action_item in record.action_items[:MAX_FILTERED_FIELD_ITEMS]:
        filtered_action_item = filter_output(action_item)
        if filtered_action_item.injection_flagged:
            return None
        filtered_action_items.append(filtered_action_item.text)

    return Record(
        summary=filtered_summary.text,
        key_facts=filtered_key_facts,
        action_items=filtered_action_items,
        memory_kinds=record.memory_kinds,
    )


def _dialog_recorder_prompt_messages(messages: list[str]) -> list[ChatMessage]:
    """Build the dialog recorder prompt messages for one compression call."""
    return [
        ChatMessage(role="system", content=DIALOG_RECORDER_SYSTEM_PROMPT),
        ChatMessage(role="user", content="\n---\n".join(messages)),
    ]


def _dialog_recorder_trace_context(
    *,
    model: str,
    chat_messages: list[ChatMessage],
) -> dict[str, object]:
    """Build the initial dialog recorder LLM trace context."""
    return {
        "model": model,
        "prompt": [
            {"role": message.role, "content": message.content}
            for message in chat_messages
        ],
        "raw_output": "",
    }


def _dialog_recorder_trace_entry(
    *,
    decision: str,
    messages: list[str],
    conversation_id: str,
    session_id: str,
    source_message_ids: list[str] | None,
    trace_context: dict[str, object] | None = None,
    record: Record | None = None,
    record_id: str | None = None,
    injection_flagged: bool = False,
    detail: str | None = None,
) -> dict[str, object]:
    """Build one structured dialog recorder trace entry."""
    entry: dict[str, object] = {
        "decision": decision,
        "conversation_id": conversation_id,
        "session_id": session_id,
        "source_message_ids": source_message_ids or [],
        "messages": messages,
        "message_count": len(messages),
        "injection_flagged": injection_flagged,
    }
    if trace_context:
        entry.update(trace_context)
    if record is not None:
        entry.update(
            {
                "summary": record.summary,
                "key_facts": record.key_facts,
                "action_items": record.action_items,
                "memory_kinds": [
                    memory_kind.value for memory_kind in record.memory_kinds
                ],
            }
        )
    if record_id:
        entry["record_id"] = record_id
    if detail:
        entry["detail"] = detail
    return entry


async def _compress_messages_with_trace(
    provider: OllamaProvider,
    messages: list[str],
) -> tuple[Record | None, dict[str, object]]:
    """Compress messages into a structured record with trace metadata.

    Calls the dialog recorder model to generate a plain-text record.
    Returns None if the LLM output fails validation.

    Works with any provider that has a ``chat()`` method and a
    ``dialog_recorder_model`` attribute (OllamaProvider, OpenRouterProvider).

    Args:
        provider: LLM provider for inference.
        messages: List of message texts to compress.

    Returns:
        Tuple of parsed record and trace metadata.
    """
    chat_messages = _dialog_recorder_prompt_messages(messages)
    trace_context = _dialog_recorder_trace_context(
        model=provider.dialog_recorder_model,
        chat_messages=chat_messages,
    )
    try:
        logger.info(
            "Dialog recorder LLM call started (model=%s)",
            provider.dialog_recorder_model,
        )
        response = await provider.chat(
            chat_messages,
            model=provider.dialog_recorder_model,
            max_tokens=DIALOG_RECORDER_MAX_TOKENS,
            temperature=DIALOG_RECORDER_TEMPERATURE,
            enable_thinking=False,
        )
        logger.debug("Dialog recorder raw response: %.2000s", response.content)
        trace_context["raw_output"] = response.content
        record = _parse_observation(response.content)
        if record is None:
            trace_context["decision"] = TRACE_DECISION_PARSE_FAILED
        return record, trace_context
    except Exception as error:
        logger.exception("Dialog recorder LLM call failed")
        trace_context["decision"] = TRACE_DECISION_LLM_ERROR
        trace_context["error"] = str(error)
        return None, trace_context


async def compress_messages(
    provider: OllamaProvider,
    messages: list[str],
) -> Record | None:
    """Compress messages into a structured record."""
    record, _trace_context = await _compress_messages_with_trace(
        provider,
        messages,
    )
    return record


async def _write_dialog_recorder_trace(
    decision: str,
    db_client: object,
    messages: list[str],
    conversation_id: str,
    session_id: str,
    source_message_ids: list[str] | None,
    trace_context: dict[str, object] | None = None,
    record: Record | None = None,
    record_id: str | None = None,
    injection_flagged: bool = False,
    detail: str | None = None,
) -> None:
    """Write a structured dialog recorder trace entry for diagnostics."""
    entry = _dialog_recorder_trace_entry(
        decision=decision,
        messages=messages,
        conversation_id=conversation_id,
        session_id=session_id,
        source_message_ids=source_message_ids,
        trace_context=trace_context,
        record=record,
        record_id=record_id,
        injection_flagged=injection_flagged,
        detail=detail,
    )
    append_dialog_recorder_trace(entry)
    try:
        await db_client.write_record_processing_diagnostic(
            decision=decision,
            conversation_id=conversation_id,
            session_id=session_id,
            record_id=record_id or "",
            model=str(entry.get("model", "")),
            message_count=int(entry.get("message_count", 0)),
            source_message_ids=[str(item) for item in source_message_ids or []],
            messages=[str(item) for item in messages],
            injection_flagged=injection_flagged,
            summary=str(entry.get("summary", "")),
            key_facts=[str(item) for item in entry.get("key_facts", [])],
            action_items=[str(item) for item in entry.get("action_items", [])],
            memory_kinds=[str(item) for item in entry.get("memory_kinds", [])],
            prompt=list(entry.get("prompt", [])),
            raw_output=str(entry.get("raw_output", "")),
            error=str(entry.get("error", "")),
            detail=str(entry.get("detail", "")),
        )
    except Exception:
        logger.warning("Failed to write record processing diagnostic", exc_info=True)


def _dialog_recorder_text_messages(messages: list[str]) -> tuple[list[str], bool]:
    """Normalize dialog recorder input into text-only messages and injection state."""
    from backend.ipc.models import extract_text_content

    text_messages = [
        extract_text_content(message) if not isinstance(message, str) else message
        for message in messages
    ]
    combined = _normalize_role_labels_for_filter(text_messages)
    input_result = filter_input(combined)
    return text_messages, input_result.injection_flagged


async def _write_skip_trace(
    *,
    decision: str,
    db_client: object,
    text_messages: list[str],
    conversation_id: str,
    session_id: str,
    source_message_ids: list[str] | None,
    trace_context: dict[str, object] | None = None,
    record: Record | None = None,
    injection_flagged: bool = False,
) -> None:
    """Write one dialog recorder trace for a skipped record path."""
