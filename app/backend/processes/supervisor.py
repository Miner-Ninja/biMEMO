"""biMEMO process supervisor entry point.

Spawns and monitors isolated processes in dependency order:
DB Proxy → [Signing Proxy, Credential Proxy, Orchestrator] → FastAPI.
Each process gets its own HMAC secrets for IPC authentication,
generated by the supervisor and passed via process arguments.

The supervisor is the container entrypoint in multi-process mode.
It handles SIGTERM for graceful shutdown and restarts crashed
processes up to a configurable limit.
"""

import asyncio
import logging
import os
import secrets
import signal
from typing import TYPE_CHECKING

from backend.ipc.supervisor import (
    ProcessSpec,
    ProcessSupervisor,
    SupervisorError,
)
from backend.processes.targets import (
    CREDENTIAL_PROXY_SOCKET,
    DB_PROXY_SOCKET_A,
    DB_PROXY_SOCKET_B,
    DB_PROXY_SOCKET_C,
    ORCHESTRATOR_SOCKET,
    SIGNING_PROXY_SOCKET,
    _credential_proxy_target,
    _db_proxy_target,
    _ensure_socket_dir,
    _fastapi_target,
    _make_socket_probe,
    _orchestrator_target,
    _signing_proxy_target,
)


if TYPE_CHECKING:
    from backend.config import Settings
    from backend.security.startup_state import StartupState


logger = logging.getLogger(__name__)
IPC_SECRET_NAMES = (
    "db-proxy",
    "db-proxy-b",
    "db-proxy-c",
    "signing-proxy",
    "credential-proxy",
    "orchestrator",
)


# ============================================================
# Process topology
# ============================================================


def build_topology(startup_password: str | None = None) -> list[ProcessSpec]:
    """Define the biMEMO process topology.

    Args:
        startup_password: Optional manual startup password kept in process memory.

    Returns:
        List of ProcessSpec in dependency order:
        DB Proxy → [Signing Proxy, Credential Proxy, Orchestrator] → FastAPI.
    """
    _ensure_socket_dir()

    return [
        ProcessSpec(
            name="db-proxy",
            target=_db_proxy_target,
            args_factory=lambda secrets: (
                DB_PROXY_SOCKET_A,
                secrets["db-proxy"],
                DB_PROXY_SOCKET_B,
                secrets["db-proxy-b"],
                DB_PROXY_SOCKET_C,
                secrets["db-proxy-c"],
                startup_password,
            ),
            health_check=_make_socket_probe(DB_PROXY_SOCKET_A),
        ),
        ProcessSpec(
            name="signing-proxy",
            target=_signing_proxy_target,
            args_factory=lambda secrets: (
                SIGNING_PROXY_SOCKET,
                secrets["signing-proxy"],
                DB_PROXY_SOCKET_B,
                secrets["db-proxy-b"],
                startup_password,
            ),
            depends_on=["db-proxy"],
            health_check=_make_socket_probe(SIGNING_PROXY_SOCKET),
        ),
        ProcessSpec(
            name="credential-proxy",
            target=_credential_proxy_target,
            args_factory=lambda secrets: (
                CREDENTIAL_PROXY_SOCKET,
                secrets["credential-proxy"],
                DB_PROXY_SOCKET_C,
                secrets["db-proxy-c"],
            ),
            depends_on=["db-proxy"],
            health_check=_make_socket_probe(CREDENTIAL_PROXY_SOCKET),
        ),
        ProcessSpec(
            name="orchestrator",
            target=_orchestrator_target,
            args_factory=lambda secrets: (
                DB_PROXY_SOCKET_A,
                secrets["db-proxy"],
                ORCHESTRATOR_SOCKET,
                secrets["orchestrator"],
            ),
            depends_on=["db-proxy"],
            health_check=_make_socket_probe(ORCHESTRATOR_SOCKET),
        ),
        ProcessSpec(
            name="fastapi",
            target=_fastapi_target,
            args_factory=lambda secrets: (
                ORCHESTRATOR_SOCKET,
                secrets["orchestrator"],
                DB_PROXY_SOCKET_B,
                secrets["db-proxy-b"],
                CREDENTIAL_PROXY_SOCKET,
                secrets["credential-proxy"],
                SIGNING_PROXY_SOCKET,
                secrets["signing-proxy"],
            ),
            depends_on=["orchestrator", "credential-proxy", "signing-proxy"],
        ),
    ]


# ============================================================
# Supervisor main
# ============================================================


def _generate_secrets() -> dict[str, bytes]:
    """Generate HMAC secrets for all IPC channels.

    Returns:
        Dict mapping channel name to 32-byte secret.
    """
    return {name: secrets.token_bytes(32) for name in IPC_SECRET_NAMES}


def _build_supervisor(startup_password: str | None = None) -> ProcessSupervisor:
    """Create one supervisor and register the full process topology."""
    supervisor = ProcessSupervisor()
    for spec in build_topology(startup_password):
        supervisor.add_process(spec)
    supervisor.set_secrets(_generate_secrets())
    return supervisor


def _register_shutdown_signals(
    shutdown: asyncio.Event,
) -> None:
    """Attach SIGTERM and SIGINT handlers to one shutdown event."""
    loop = asyncio.get_running_loop()
    loop.add_signal_handler(signal.SIGTERM, shutdown.set)
    loop.add_signal_handler(signal.SIGINT, shutdown.set)


async def _startup_password_from_gate(
    settings: Settings,
    startup_state: StartupState,
) -> str | None:
    """Run the startup gate for states that need manual password input."""
    from backend.processes.startup_gate import run_startup_gate
    from backend.security.startup_state import StartupState

    if startup_state in {
        StartupState.SETUP,
        StartupState.LOCKED,
        StartupState.AUTO_UNLOCK_FAILED,
    }:
        return await run_startup_gate(settings, startup_state)
    return None


async def _start_supervisor_with_password_retry(
    *,
    settings: Settings,
    startup_state: StartupState,
) -> ProcessSupervisor:
    """Start the supervisor, using the startup gate after missing or bad passwords."""
    from backend.security.startup_state import StartupState

    manual_password = await _startup_password_from_gate(settings, startup_state)

    while True:
        supervisor = _build_supervisor(manual_password)
        try:
            await supervisor.start()
            return supervisor
        except SupervisorError:
            await supervisor.shutdown()
            if startup_state not in {
                StartupState.AUTO_UNLOCK,
                StartupState.LOCKED,
                StartupState.AUTO_UNLOCK_FAILED,
            }:
                raise
            logger.warning("Password startup failed; waiting for manual unlock")
            startup_state = StartupState.AUTO_UNLOCK_FAILED
            manual_password = await _startup_password_from_gate(settings, startup_state)


def supervisor_main() -> None:
    """Run the biMEMO process supervisor.

    This is the container entrypoint for multi-process mode.
    Spawns all processes in dependency order and monitors them.
    """
    from backend.config import get_settings
    from backend.logging_config import configure_logging
    from backend.security.startup_state import determine_startup_state

    settings = get_settings()
    configure_logging(settings.debug)

    async def run() -> None:
        """Start supervisor and wait for shutdown."""
        shutdown = asyncio.Event()
        _register_shutdown_signals(shutdown)

        startup_state = determine_startup_state(settings)
        logger.info("biMEMO startup state: %s", startup_state.value)
        supervisor = await _start_supervisor_with_password_retry(
            settings=settings,
            startup_state=startup_state,
        )
        logger.info("biMEMO supervisor running (pid=%d)", os.getpid())

        await shutdown.wait()
        logger.info("Shutdown signal received")
        await supervisor.shutdown()

    asyncio.run(run())


if __name__ == "__main__":
    supervisor_main()
